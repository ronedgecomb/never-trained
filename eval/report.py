#!/usr/bin/env python3
"""Writes RESULTS.md from the stored evaluation logs.

Every number in the tables is read from eval/results/*/summary.json (which is
itself derived from episodes.csv), policy/weights/manifest.json and
eval/FROZEN.json. Nothing is typed in by hand.

Usage: python eval/report.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

NAMES = {
    "authored": "**Authored** (written by Claude, no training)",
    "naive_tracker": "Naive tracker (authored baseline)",
    "pufferai_pretrained": "PufferAI pretrained (trained with RL)",
    "random": "Random actions",
}
ORDER = ["authored", "pufferai_pretrained", "naive_tracker", "random"]


def load(phase: str) -> dict:
    return json.loads((REPO / f"eval/results/{phase}/summary.json").read_text())


def table(summary: dict, protocol: str) -> str:
    rows = ["| Policy | Mean score ± SD | 95% CI of mean | Min | Games cleared (95% CI) | "
        "Balls lost / game | Mean frames | Distinct trajectories |",
        "|---|---|---|---|---|---|---|---|"]
    for key in ORDER:
        s = summary.get(f"{key}/{protocol}")
        if not s:
            continue
        lo, hi = s["score_mean_ci95"]
        wl, wh = s["clear_rate_ci95"]
        rows.append(
            f"| {NAMES[key]} | {s['score_mean']:.1f} ± {s['score_std']:.1f} | "
            f"{lo:.1f} – {hi:.1f} | {s['score_min']:.0f} | "
            f"{s['cleared']} / {s['episodes']} ({100 * wl:.0f}–{100 * wh:.0f}%) | "
            f"{s['balls_lost_mean']:.2f} | {s['frames_mean']:,.0f} | "
            f"{s['distinct_trajectories']} |")
    return "\n".join(rows)


def main() -> None:
    final = load("final")
    dev = load("dev")
    dev300 = load("dev300")
    frozen = json.loads((REPO / "eval/FROZEN.json").read_text())
    manifest = json.loads((REPO / "policy/weights/manifest.json").read_text())["authored_breakout"]
    check = json.loads((REPO / "eval/results/final/reproduction_check.json").read_text())
    stock = (REPO / "eval/results/stock_binary.txt").read_text().strip()
    import csv
    import re
    with open(REPO / "eval/results/final/episodes.csv") as f:
        shown = next(r for r in csv.DictReader(f) if r["policy"] == "authored"
            and r["protocol"] == "standard" and r["seed"] == "1001")
    failures = (REPO / "eval/results/dev/sticky_failures.txt").read_text()
    fail = [int(x) for x in re.findall(r":\s*(\d+)\s*$", failures, flags=re.M)[:5]]
    fs = final["summary"]
    a, p = fs["authored/standard"], fs["pufferai_pretrained/standard"]
    a_s, p_s = fs["authored/sticky25"], fs["pufferai_pretrained/sticky25"]

    text = f"""# Results

Generated by `eval/report.py` from the logs in `eval/results/`. Protocol:
[`eval/PROTOCOL.md`](eval/PROTOCOL.md). Development history:
[`REVISIONS.md`](REVISIONS.md).

## Headline

On {a['episodes']} held-out games of PufferLib Breakout (seeds
{final['seeds'][0]}–{final['seeds'][1]}, standard environment), the authored
network scored **{a['score_mean']:.0f} / 864 in every game**
({a['cleared']}/{a['episodes']} cleared) and lost **{a['balls_lost_mean']:.2f} balls per game**.
PufferAI's published trained checkpoint, the same architecture run by the same
code, averaged {p['score_mean']:.1f}, cleared {p['cleared']}/{p['episodes']} and lost
{p['balls_lost_mean']:.2f} balls per game. Random play averaged
{fs['random/standard']['score_mean']:.1f}.

Under the sticky-action stress test the authored network averaged
{a_s['score_mean']:.1f} ({a_s['cleared']}/{a_s['episodes']} cleared) and the trained
checkpoint {p_s['score_mean']:.1f} ({p_s['cleared']}/{p_s['episodes']} cleared).

## What was evaluated

| | |
|---|---|
| Environment | {final['environment']['library']}, commit `{final['environment']['pufferlib_commit'][:12]}` |
| Configuration | {final['environment']['config']} (576×330 field, 18×6 bricks, `frameskip = 3`, discrete actions) |
| Episode | Until 864 points or the sixth lost ball. Harness cap {final['max_agent_steps_per_episode']:,} agent steps ({final['max_agent_steps_per_episode'] * 3:,} frames); no episode reached it |
| Return | Episode return = score (7, 4 or 1 points per brick; 216 bricks; maximum 864) |
| Final seeds | {final['seeds'][0]}–{final['seeds'][1]}: {final['episodes_per_cell']} episodes per policy and protocol |
| Development seeds | 1–20 (all policies and protocols), 1–300 (authored, standard) |
| Authored model | PufferNet, hidden {manifest['hidden_size']}, {manifest['num_layers']} layers: {manifest['parameters']:,} parameters, {manifest['nonzero_parameters']} non-zero; 64,768-byte checkpoint |
| Reference model | PufferAI's `breakout_weights.bin`: same architecture and parameter count |
| Development revisions | {frozen['revision']} (the first version; never changed after its first rollout) |
| Frozen | {frozen['frozen_utc']}, sha256 `{frozen['authored_weights_sha256'][:16]}…`; final run started {final['started_utc']} |

## Final evaluation (held-out seeds)

### Standard environment (primary)

{table(fs, 'standard')}

### Stress test: sticky actions (p = 0.25)

Each agent step, with probability 0.25 the previously applied action is
repeated instead of the policy's choice. Neither network was built or trained
for this, and the authored weights were not changed in response to it.

{table(fs, 'sticky25')}

### Greedy decoding (argmax instead of PufferLib's softmax sampling)

{table(fs, 'greedy')}

Scores are bounded at 864, so a standard deviation of 0.0 means every episode
reached the maximum. Confidence intervals: bootstrap (10,000 resamples) for
the mean, Wilson for the clear rate. "Mean frames" is the mean episode length
in simulated frames at 60 Hz; for the authored policy, which clears every
standard game, it is also the mean time to clear
({a['frames_to_clear_mean']:,.0f} frames; the trained checkpoint takes
{p['frames_to_clear_mean']:,.0f} frames in the games it clears).

## Development evaluation (seeds 1–20)

{table(dev['summary'], 'standard')}

Sticky actions:

{table(dev['summary'], 'sticky25')}

Wider check of the authored policy alone, standard environment, seeds 1–300:
{dev300['summary']['authored/standard']['cleared']} / {dev300['summary']['authored/standard']['episodes']} cleared,
{dev300['summary']['authored/standard']['balls_lost_mean']:.2f} balls lost per game.

## Independent check with PufferLib's stock evaluator

`eval/stock_check.sh` runs PufferLib's own `./breakout WEIGHTS --headless
--eval_episodes=100` (no harness of ours; its own seeding, episodes back to
back):

```
{stock}
```

## Reproducibility check

After the final run the harness sources were reorganised: the episode runner
moved into `harness/bk_common.h`. `python eval/run_eval.py --phase final --verify`
re-ran all {check['episodes_compared']:,} final episodes with the reorganised harness:
{'every row is identical to the stored log' if check['identical'] else 'ROWS DIFFER'}
(`eval/results/final/reproduction_check.json`).

## How to read these numbers

**The standard environment is nearly deterministic.** Its only randomness is
the serve direction. A policy that never loses a ball sees one serve per
episode, so with greedy decoding the authored policy has exactly
{fs['authored/greedy']['distinct_trajectories']} distinct games (serve left, serve right),
both perfect. PufferLib samples actions from the softmax, which adds a little
variation near decision boundaries: {a['distinct_trajectories']} distinct action sequences
in the {a['episodes']} standard final episodes, but only a handful of distinct
outcomes. "100 of 100" therefore mostly says the policy is flawless on the two
games the standard environment can produce. The sticky-action protocol is
where every seed is a genuinely different game.

**Score saturates.** The naive ball-follower also clears every standard game
({fs['naive_tracker/standard']['cleared']}/{fs['naive_tracker/standard']['episodes']}), losing
{fs['naive_tracker/standard']['balls_lost_mean']:.2f} balls per game. What separates the
policies in the standard environment is balls lost
({a['balls_lost_mean']:.2f} / {fs['naive_tracker/standard']['balls_lost_mean']:.2f} /
{p['balls_lost_mean']:.2f}) and whether six balls are enough to finish; under
sticky actions the gap is large
({a_s['score_mean']:.0f} / {fs['naive_tracker/sticky25']['score_mean']:.0f} / {p_s['score_mean']:.0f}).

**Representative success.** Final seed 1001 (the first held-out seed):
{shown['score']} points, {int(shown['frames']):,} frames, {shown['balls_lost']} balls lost,
{shown['paddle_hits']} paddle contacts.

**Failure cases.** None in the standard environment (400 development and final
episodes). Under sticky actions the authored policy lost
{a_s['balls_lost_mean']:.2f} balls per game and failed to clear
{a_s['episodes'] - a_s['cleared']} of {a_s['episodes']} games (worst score {a_s['score_min']:.0f}).
`eval/failure_analysis.py` examines every lost ball on the development seeds:
{fail[1]} of {fail[0]} were preceded by at least two overridden actions in the final eight
steps (the paddle is carried past the landing point with no time to return);
{fail[4]} involved a ball travelling more than 70° from vertical after an earlier
off-centre contact. See `eval/results/dev/sticky_failures.txt`.

## Limitations

- It is an analytic controller compiled into weights, not a learned policy. It
  works because the environment's source code states the physics exactly; the
  constants (field size, paddle speed, frameskip) are baked in.
- It reads the simulator's 118-number state observation, not pixels.
- It ignores the 108 brick inputs and does not aim. It clears the board because
  it never misses, not because it plans; late in each wall it waits for the
  ball to find the last bricks.
- The recurrent state of the network is unused (the gates are saturated), so
  the policy is purely feed-forward.
- The trained reference is a published checkpoint; its exact training run is
  not documented alongside the file. PufferLib's Breakout config specifies
  55 million training steps.
- Results are for this simulator and configuration only.
"""
    (REPO / "RESULTS.md").write_text(text)
    print("wrote RESULTS.md")


if __name__ == "__main__":
    main()
